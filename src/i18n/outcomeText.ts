const tables: Record<Locale, Table> = { en, az, ru: {} };

export function ot(locale: Locale | undefined, key: string, vars?: Record<string, string | number | null | undefined>): string {
  let s = tables[locale ?? "en"]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v === null || v === undefined ? "" : String(v));
  return s;
}

export function nextActionLabel(locale: Locale | undefined, code: string | null | undefined): string {
  if (!code) return "—";
  const s = ot(locale, `na.${code}`);
  return s.charAt(0).toUpperCase() + s.slice(1);
}
