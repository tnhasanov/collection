export const dictionaries: Record<Locale, DeepPartial<Dictionary>> = { en, az, ru };

function lookup(obj: unknown, path: string[]): string | undefined {
  let cur: unknown = obj;
  for (const p of path) {
    if (cur && typeof cur === "object" && p in (cur as Record<string, unknown>)) cur = (cur as Record<string, unknown>)[p];
    else return undefined;
  }
  return typeof cur === "string" ? cur : undefined;
}

/** Translate a dotted key, falling back to English and finally to the key itself. `{name}` placeholders are filled from vars. */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const path = key.split(".");
  let s = lookup(dictionaries[locale], path) ?? lookup(en, path) ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return s;
}

export function isLocale(v: string | undefined | null): v is Locale {
  return v === "en" || v === "az" || v === "ru";
}

