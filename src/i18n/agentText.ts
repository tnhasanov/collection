const tables: Record<Locale, Table> = { en, az, ru };

export function at(locale: Locale | undefined, key: string, vars?: Record<string, string | number | null | undefined>): string {
  let s = tables[locale ?? "en"]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v === null || v === undefined ? "" : String(v));
  return s;
}

/** Agent-facing text for an API error: the code-specific translation, else the server message. */
export function errorText(locale: Locale, error: { code?: string; message?: string; details?: unknown } | null | undefined): string {
  if (!error) return at(locale, "err.generic");
  const detailCode = (error.details as { code?: string } | null | undefined)?.code;
  for (const code of [detailCode, error.code]) if (code && tables.en[`err.${code}`]) return at(locale, `err.${code}`);
  if (error.message === "SMS blocked by contact policy") return at(locale, "err.SMS_BLOCKED");
  return locale === "en" ? error.message ?? at(locale, "err.generic") : at(locale, "err.generic") + (error.message ? ` (${error.message})` : "");
}
